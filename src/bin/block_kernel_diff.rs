//! Compare BLVM `connect_block` vs Bitcoin Core `libbitcoinkernel` for each mainnet block from the chunk cache.
//!
//! **Full-chain Phase 2 (block accept/reject):** paired with `sort_merge_test` step 6 (Phase 1, scripts).
//! Together they form the complete mainnet differential; scripts are skipped below assume-valid on
//! **both** sides here because Phase 1 already covers them. See **`docs/FULL_CHAIN_DIFFERENTIAL.md`**.
//!
//! ## Paths (defaults -- no env required)
//! - **Chunk cache**: **`--block-cache-dir`** > `BLOCK_CACHE_DIR` > `~/.local/share/blvm-kernel-diff/chunk-cache` if it has `chunks.meta` > XDG chunk cache (`get_chunks_dir`).
//! - **Core datadir**: **`--core-datadir`** > `CORE_DIFF_DATADIR` > **`~/.local/share/blvm-kernel-diff/core-datadir`**.
//!
//! **`chunks.meta`** may live at the cache root (**flat**) or under **`chunks/`** (nested).
//!
//! ## Bootstrap (one-time)
//! `libbitcoinkernel` needs a **block index** covering all heights you want to compare. Build once:
//! - **Option A**: `block_kernel_diff --start 0 --core-datadir /path/to/baseline` (full run 0->tip).
//! - **Option B**: Run `bitcoind -datadir /path/to/baseline`, let it IBD, stop.
//! After the block index exists, subsequent runs **wipe coins + import snapshot** (no block replay).
//! Set `CORE_BLOCK_INDEX_DIR` (for the parallel lanes script) to this baseline path.
//!
//! ## Resume (BLVM checkpoints)
//! **`{--checkpoint-dir}/`** must contain **`utxo_0.bin`** and the **`delta_*`** ladder
//! (generated by `chunk_utxo_checkpoints --delta-checkpoints --base-every 0`).
//! Match **`differential_checkpoints_fixed_v1`** vs default via **`UTXO_CHECKPOINT_DIR`**.
//!
//! ### BLVM side (default: delta ladder)
//! BLVM reconstructs state at H from **`utxo_0.bin`** + the delta chain in-memory.
//! Use **`--blvm-prefer-utxo-snapshot`** to load **`utxo_H.bin`** directly.
//! Requires **`--blvm-checkpoint-height H`** + **`--start H+1`**.
//! When Core tip > H, BLVM pre-rolls H+1..tip locally (no kernel calls), both compare from tip+1.
//!
//! ### Core side (two modes)
//! **Sequential** (Core already at H): point `CORE_DIFF_DATADIR` at a datadir synced to H. Done.
//!
//! **Wipe + snapshot import** (parallel lanes, no block replay):
//! ```text
//! block_kernel_diff \
//!   --blvm-checkpoint-height 400000 \
//!   --start 400001 --end 500001 \
//!   --wipe-chainstate-db \
//!   --import-from-deltas
//! ```
//! Opens Core with coins DB wiped (block index kept), materializes `utxo_400000.bin` from
//! `utxo_0 + delta_*` if absent, imports into Core, then compares H+1..end.
//! BLVM does the same reconstruction in-memory. Both sides start from identical state.
//! Use **`--import-blvm-snapshot /path`** + **`--wipe-chainstate-db`** for an explicit file.
//!
//! ## Parallel lanes
//! See **`scripts/kernel-diff-parallel-lanes.sh`**. Set `CORE_BLOCK_INDEX_DIR` to the baseline;
//! pass `<checkpoint_height> <end>` pairs. Each lane copies the block index, wipes coins,
//! imports snapshot from delta ladder, runs comparison concurrently in its own Core datadir.
//!
//! ## Checkpointing during compare
//! **`--checkpoint-every N`** writes **`utxo_height.bin`** every N heights.
//! **`--utxo-checkpoint-format`**: `bincode` (fast Rust default) or `fixed-v1` (Core interchange).
//!
//! ## BLVM header / PoW parity in this tool
//! - Rolling window of up to **11 parent headers** feeds `BlockValidationContext` so BIP113 median
//!   time-past and header timestamp bounds use a real `time_context` (not `None`).
//! - `blvm_protocol::pow::check_proof_of_work` runs **before** `connect_block` (cheap per block).
//! - **`nBits`**: mainnet genesis uses `MAX_TARGET`; between retargets, `nBits` must match parent;
//!   at each 2016-height boundary, `get_next_work_required` over the prior 2016 headers (deque + rare reload).
//!
//! ## Speed
//! - Release build, fast SSD for **`CORE_DIFF_DATADIR`**.
//! - **`--worker-threads`** / **`BLOCK_KERNEL_WORKER_THREADS`** (0-15): Core kernel parallel validation.
//! - **`RAYON_NUM_THREADS`** / **`BLVM_SCRIPT_WORKERS`**: BLVM-side parallelism (script-heavy ranges).
//! - **`--kernel-blocktree-ram`** / **`--kernel-chainstate-ram`**: keep LevelDB in RAM.
//! - **Env file** (gitignored **`kernel-diff.local.env`**, **`.env.local`**, or **`KERNEL_DIFF_ENV_FILE`**):
//!   [`load_kernel_diff_env`](blvm_bench::kernel_diff_paths::load_kernel_diff_env) runs before CLI
//!   parse; set **`BITCOIN_RPC_HOST`** for LAN Core (Start9) or rely on **`START9_RPC_*`** fallbacks
//!   in [`RpcConfig::from_env`](blvm_bench::node_rpc_client::RpcConfig::from_env). Chunk RPC fallback
//!   prefetches the next block while the current block is validated.
//! - **`KERNEL_DIFF_CHUNK_READAHEAD`** (default **8**): bounded channel depth between the chunk
//!   reader thread and the compare loop (`2`–`64`). Higher ⇒ more raw blocks queued while BLVM or
//!   RocksDB is slow on the current block (smoother throughput; more RAM for queued `Vec<u8>`).
//!
//! ## RAM
//! - This binary is linked with **mimalloc** (via `--features bitcoinkernel`) to lower peak RSS on
//!   huge `UtxoSet` maps vs glibc's allocator.
//! - **`--kernel-coins-cache-mb`** (default **50**): Core's in-memory coin cache. Reduced from the
//!   kernel default (450 MiB) since the diff only moves forward. Saves ~400 MiB.
//! - **`--core-blocks-dir`** (env `CORE_DIFF_BLOCKS_DIR`): separate dir for `blk*.dat`/`rev*.dat`.
//!   Set to a large non-tmpfs location when `--core-datadir` is in `/tmp`; block files grow ~128 MiB
//!   per 50k blocks and will exhaust a small ramdisk.
//! - **`--disk-utxo-path`** (env `BLOCK_KERNEL_DIFF_DISK_UTXO_PATH`): RocksDB for BLVM's UTXO set.
//!   Caps BLVM's RSS to ~512 MiB (RocksDB block cache) regardless of chain height. Without this,
//!   in-memory UTXO grows to 1–4 GiB by height 300k. Set `DISK_UTXO_OVERLAY_CAP=200000` and
//!   `DISK_UTXO_COMMIT_INTERVAL=200` for the tightest memory profile.
//! - **`--mem-available-floor-mb 0`** (default): do **not** stop early from `MemAvailable` — add RAM
//!   or swap/zram if the OOM killer hits; set the floor **>0** only if you prefer a graceful stop.
//! - **`--mem-available-recovery-passes`** (default **3** when using the restart script): before
//!   exiting on a low `MemAvailable` reading, the binary runs `malloc_trim`, **`mi_collect`**, and a
//!   durable **disk-UTXO overlay flush** (when `--disk-utxo-path` is set); if memory recovers, it
//!   **keeps going in the same process** without wrapper restart.
//! - **`--mem-available-recovery-slop-mb`** (default **150** with the restart script): after recovery,
//!   treat `MemAvailable` as sufficient if it is ≥ **`floor − slop`** (page-cache jitter vs a strict
//!   numeric floor).
//! - After each BLVM checkpoint, **`malloc_trim**(0)` runs on Linux to return freed heap to the OS.

